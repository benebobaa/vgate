/**
 * Compiles the CLI into standalone binaries that carry the agent skills (and, through cli/runtime.ts when it exists,
 * whatever else the binary must embed).
 *
 *   bun cli/build.ts                          dist/vgate, for this machine
 *   bun cli/build.ts --target bun-linux-x64   dist/vgate-linux-x64
 *   bun cli/build.ts --all                    every platform of cli/release-config.ts, packed for release into
 *                                             dist/release/v<version>/: one tar.gz per platform, SHA256SUMS,
 *                                             manifest.json (and SHA256SUMS.minisig with VGATE_MINISIGN_KEY);
 *                                             dist/release/ is laid out exactly like the bucket
 *
 * Embedded values travel as global constants (`declare const VGATE_X: string | undefined` where they are read). They
 * are set by a generated module that the entry imports before cli/main.ts, not by `--define`, so their size is not
 * bounded by the command line. Builder hook: an optional cli/runtime.ts exporting
 *   buildDefines(root: string): Record<string, string> | Promise<Record<string, string>>
 * adds constants: each key becomes a global holding that string.
 *
 * The compiler is Bun; this script itself is plain Node-compatible TypeScript (it only spawns `bun`, `tar`,
 * `codesign` and `minisign`).
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gunzipSync } from 'node:zlib';
import { parseArgs, str } from '../framework/cli/args.ts';
import {
  assetName,
  BASE_URL,
  NAME,
  PLATFORMS,
  platformId,
  VERSION_PATTERN,
  versionDir,
  type Platform,
} from './release-config.ts';
import { readSkills } from './skills.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = parseArgs(process.argv.slice(2), ['all']);

function die(message: string): never {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

function run(command: string, argv: string[], cwd = root): void {
  const result = spawnSync(command, argv, { cwd, stdio: 'inherit' });
  if (result.error) die(`Could not run ${command}: ${result.error.message}`);
  if (result.status !== 0) die(`${command} ${argv[0] ?? ''} failed with exit code ${result.status ?? 'null'}`);
}

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string };
if (!VERSION_PATTERN.test(version)) die(`package.json version "${version}" is not semver (x.y.z[-pre])`);

const skills = readSkills(join(root, '.claude', 'skills'));
if (Object.keys(skills).length === 0)
  die('No skills under .claude/skills: refusing to build a binary that carries none');

async function extraConstants(): Promise<Record<string, string>> {
  const file = join(root, 'cli', 'runtime.ts');
  if (!existsSync(file)) return {};
  const mod = (await import(pathToFileURL(file).href)) as {
    buildDefines?: (root: string) => Record<string, string> | Promise<Record<string, string>>;
  };
  return mod.buildDefines ? await mod.buildDefines(root) : {};
}

const constants: Record<string, string> = {
  VGATE_SKILLS: JSON.stringify(skills),
  VGATE_VERSION: version,
  ...(await extraConstants()),
};
for (const name of Object.keys(constants)) {
  if (!/^[A-Z][A-Z0-9_]*$/.test(name)) die(`Embedded constant "${name}" must be an UPPER_SNAKE identifier`);
}

// The generated entry: constants first (imports evaluate in order), then the CLI.
const buildDir = join(root, 'dist', '.build');
mkdirSync(buildDir, { recursive: true });
writeFileSync(
  join(buildDir, 'constants.ts'),
  `// Generated by cli/build.ts; do not edit.\nconst g = globalThis as Record<string, unknown>;\n${Object.entries(
    constants,
  )
    .map(([name, value]) => `g.${name} = ${JSON.stringify(value)};`)
    .join('\n')}\n`,
);
const mainImport = relative(buildDir, join(root, 'cli', 'main.ts'))
  .split('\\')
  .join('/');
writeFileSync(join(buildDir, 'entry.ts'), `import './constants.ts';\nimport '${mainImport}';\n`);

function compile(outfile: string, bunTarget?: string): void {
  mkdirSync(dirname(outfile), { recursive: true });
  run('bun', [
    'build',
    '--compile',
    // The gate must give the same answer everywhere: no stray .env or bunfig.toml of the cwd may change it.
    '--no-compile-autoload-dotenv',
    '--no-compile-autoload-bunfig',
    ...(bunTarget ? ['--target', bunTarget] : []),
    join(buildDir, 'entry.ts'),
    '--outfile',
    outfile,
  ]);
  // Apple Silicon refuses to run an unsigned arm64 binary; an ad-hoc signature is enough for a curl-installed tool.
  if (bunTarget?.startsWith('bun-darwin') && process.platform === 'darwin') {
    run('codesign', ['--force', '--sign', '-', outfile]);
  }
}

const megabytes = (path: string) => (statSync(path).size / 1024 / 1024).toFixed(1);
const sha256 = (path: string) => createHash('sha256').update(readFileSync(path)).digest('hex');
const skillFiles = Object.values(skills).reduce((sum, skill) => sum + Object.keys(skill).length, 0);

if (args.all !== true) {
  const target = str(args.target);
  const outfile = join(root, 'dist', target ? `${NAME}-${target.replace(/^bun-/, '')}` : NAME);
  compile(outfile, target);
  process.stdout.write(
    `${relative(root, outfile)}  ${megabytes(outfile)} MB  version ${version}  ` +
      `${Object.keys(skills).length} skills (${skillFiles} files)\n`,
  );
  process.exit(0);
}

// --all: the release.
const releaseDir = join(root, 'dist', 'release', versionDir(version));
rmSync(releaseDir, { recursive: true, force: true });
mkdirSync(releaseDir, { recursive: true });

const licenseFile = join(root, 'LICENSE');
const licenseText = existsSync(licenseFile)
  ? readFileSync(licenseFile, 'utf8')
  : `${NAME} ${version}\n\nThe license of this release has not been chosen yet. Until it is, no rights beyond running\n` +
    `the binary are granted. See ${BASE_URL} for updates.\n`;

interface Asset {
  os: Platform['os'];
  arch: Platform['arch'];
  libc?: Platform['libc'];
  platform: string;
  file: string;
  /** Path relative to BASE_URL. */
  url: string;
  sha256: string;
  size: number;
}

const assets: Asset[] = [];
for (const platform of PLATFORMS) {
  const id = platformId(platform);
  const stage = join(buildDir, 'stage', id);
  rmSync(stage, { recursive: true, force: true });
  compile(join(stage, NAME), platform.bunTarget);
  writeFileSync(join(stage, 'LICENSE'), licenseText);
  const file = assetName(version, platform);
  // Explicit member order, and no macOS metadata: COPYFILE_DISABLE keeps out the ._* members, --no-xattrs the pax
  // headers bsdtar writes for extended attributes (com.apple.provenance), on which GNU tar (Fedora, Debian) warns
  // "Ignoring unknown extended header keyword" at every install. GNU tar, building on Linux, takes the same flag.
  process.env.COPYFILE_DISABLE = '1';
  run('tar', ['--no-xattrs', '-czf', join(releaseDir, file), '-C', stage, NAME, 'LICENSE'], root);
  const path = join(releaseDir, file);
  if (gunzipSync(readFileSync(path)).includes('LIBARCHIVE.xattr')) {
    die(`${file} carries extended-attribute headers: GNU tar would warn on every install`);
  }
  assets.push({
    os: platform.os,
    arch: platform.arch,
    ...(platform.libc ? { libc: platform.libc } : {}),
    platform: id,
    file,
    url: `${versionDir(version)}/${file}`,
    sha256: sha256(path),
    size: statSync(path).size,
  });
  process.stdout.write(`${file}  ${megabytes(path)} MB (binary ${megabytes(join(stage, NAME))} MB)\n`);
}

writeFileSync(join(releaseDir, 'SHA256SUMS'), assets.map((a) => `${a.sha256}  ${a.file}\n`).join(''));
const manifest = { name: NAME, version, publishedAt: new Date().toISOString(), baseUrl: BASE_URL, assets };
writeFileSync(join(releaseDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

// The pointers a release moves; release.ts uploads them last. Written next to the version so a local server of
// dist/release behaves like the bucket.
writeFileSync(join(root, 'dist', 'release', 'latest'), `${version}\n`);
writeFileSync(
  join(root, 'dist', 'release', 'latest.json'),
  `${JSON.stringify({ name: NAME, version, manifest: `${versionDir(version)}/manifest.json` }, null, 2)}\n`,
);
copyFileSync(join(root, 'scripts', 'install.sh'), join(root, 'dist', 'release', 'install.sh'));

const key = process.env.VGATE_MINISIGN_KEY;
if (key) {
  if (!existsSync(key)) die(`VGATE_MINISIGN_KEY=${key} does not exist`);
  // minisign asks for the key's password on the terminal; a CI signer uses an unencrypted key held as a secret.
  run('minisign', ['-S', '-s', key, '-m', join(releaseDir, 'SHA256SUMS'), '-t', `${NAME} ${version}`]);
  process.stdout.write('SHA256SUMS.minisig written\n');
}

process.stdout.write(
  `Release ${version}: ${assets.length} platforms in ${relative(root, releaseDir)} ` +
    `(${(assets.reduce((sum, a) => sum + a.size, 0) / 1024 / 1024).toFixed(1)} MB packed)` +
    `${key ? ', signed' : ', unsigned (set VGATE_MINISIGN_KEY to sign)'}\n`,
);
